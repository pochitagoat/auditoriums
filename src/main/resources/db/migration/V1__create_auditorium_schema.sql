-- Начальная схема аудиторного фонда. Миграция рассчитана на пустую БД PostgreSQL.
CREATE TYPE auditorium_type AS ENUM (
    'CLASSROOM',
    'COMPUTER_CLASSROOM',
    'MULTIMEDIA_LECTURE_HALL',
    'PRACTICAL_CLASSROOM',
    'SERVICE_ROOM',
    'SPECIAL_LABORATORY',
    'SPECIAL_PURPOSE_ROOM'
);

CREATE TABLE auditorium (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    type auditorium_type NOT NULL,
    description TEXT,
    capacity_students INTEGER,
    capacity_students_extra INTEGER,
    capacity_staff INTEGER,
    building VARCHAR(255),
    floor INTEGER,
    area DOUBLE PRECISION,
    has_projector BOOLEAN,
    screen_size VARCHAR(255),
    has_ac BOOLEAN,
    pc_count_manual INTEGER,
    internet BOOLEAN,
    subnet VARCHAR(255),
    in_schedule BOOLEAN,
    schedule_link VARCHAR(2048),
    actual_schedule_link VARCHAR(2048),
    last_modified TIMESTAMP WITHOUT TIME ZONE,
    changed_by VARCHAR(255),
    equipment_issue VARCHAR(2048),
    CONSTRAINT chk_auditorium_capacity_students CHECK (capacity_students >= 0),
    CONSTRAINT chk_auditorium_capacity_students_extra CHECK (capacity_students_extra >= 0),
    CONSTRAINT chk_auditorium_capacity_staff CHECK (capacity_staff >= 0),
    CONSTRAINT chk_auditorium_pc_count_manual CHECK (pc_count_manual >= 0),
    CONSTRAINT chk_auditorium_area CHECK (area >= 0)
);

CREATE TABLE auditorium_photo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auditorium_id BIGINT NOT NULL,
    file_path VARCHAR(1024) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(255),
    CONSTRAINT fk_auditorium_photo_auditorium
        FOREIGN KEY (auditorium_id) REFERENCES auditorium (id)
);

CREATE TABLE projector (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auditorium_id BIGINT NOT NULL,
    model VARCHAR(255),
    mol VARCHAR(255),
    warehouse VARCHAR(255),
    CONSTRAINT fk_projector_auditorium
        FOREIGN KEY (auditorium_id) REFERENCES auditorium (id)
);

CREATE TABLE workstation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auditorium_id BIGINT NOT NULL,
    pc_name VARCHAR(255),
    monitors VARCHAR(255),
    keyboards VARCHAR(255),
    mice VARCHAR(255),
    location_info VARCHAR(255),
    CONSTRAINT fk_workstation_auditorium
        FOREIGN KEY (auditorium_id) REFERENCES auditorium (id)
);

CREATE TABLE printer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auditorium_id BIGINT NOT NULL,
    model VARCHAR(255),
    warehouse VARCHAR(255),
    cartridge_link VARCHAR(2048),
    CONSTRAINT fk_printer_auditorium
        FOREIGN KEY (auditorium_id) REFERENCES auditorium (id)
);

CREATE TABLE department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    mol_link VARCHAR(2048)
);

CREATE TABLE additional_equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE auditorium_department (
    auditorium_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    PRIMARY KEY (auditorium_id, department_id),
    CONSTRAINT fk_auditorium_department_auditorium
        FOREIGN KEY (auditorium_id) REFERENCES auditorium (id),
    CONSTRAINT fk_auditorium_department_department
        FOREIGN KEY (department_id) REFERENCES department (id)
);

CREATE TABLE auditorium_additional_equipment (
    auditorium_id BIGINT NOT NULL,
    additional_equipment_id BIGINT NOT NULL,
    PRIMARY KEY (auditorium_id, additional_equipment_id),
    CONSTRAINT fk_auditorium_equipment_auditorium
        FOREIGN KEY (auditorium_id) REFERENCES auditorium (id),
    CONSTRAINT fk_auditorium_equipment_equipment
        FOREIGN KEY (additional_equipment_id) REFERENCES additional_equipment (id)
);

CREATE INDEX idx_auditorium_name ON auditorium (name);
CREATE INDEX idx_auditorium_type ON auditorium (type);
CREATE INDEX idx_auditorium_building_floor ON auditorium (building, floor);
CREATE INDEX idx_auditorium_photo_auditorium ON auditorium_photo (auditorium_id);
CREATE INDEX idx_projector_auditorium ON projector (auditorium_id);
CREATE INDEX idx_workstation_auditorium ON workstation (auditorium_id);
CREATE INDEX idx_printer_auditorium ON printer (auditorium_id);
CREATE INDEX idx_auditorium_department_department
    ON auditorium_department (department_id);
CREATE INDEX idx_auditorium_equipment_equipment
    ON auditorium_additional_equipment (additional_equipment_id);
