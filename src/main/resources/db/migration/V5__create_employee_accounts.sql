CREATE TABLE employee_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    position VARCHAR(255) NOT NULL,
    login VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_employee_account_full_name_not_blank CHECK (full_name ~ '[^[:space:]]'),
    CONSTRAINT chk_employee_account_position_not_blank CHECK (position ~ '[^[:space:]]'),
    CONSTRAINT chk_employee_account_login_not_blank CHECK (login ~ '[^[:space:]]')
);
