-- Существующие фотографии и их пути не изменяются.
-- Очередь сохраняет неудачную очистку и незавершенные загрузки после перезапуска.
CREATE TABLE file_cleanup_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_path VARCHAR(1024) NOT NULL UNIQUE,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attempts INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_file_cleanup_task_due ON file_cleanup_task (next_attempt_at, id);
