
-- V3__file_cleanup_tasks.sql
-- Таблица очереди задач очистки файлов.
-- Существующие фотографии и их пути не изменяются.
-- Очередь сохраняет неудачную очистку и незавершённые загрузки после перезапуска.

CREATE TABLE IF NOT EXISTS file_cleanup_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_path VARCHAR(1024) NOT NULL UNIQUE,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attempts INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_file_cleanup_task_due
    ON file_cleanup_task (next_attempt_at, id);
